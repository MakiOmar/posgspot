export function t(
  locale: ContentLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = catalogs[locale][key] ?? catalogs.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
